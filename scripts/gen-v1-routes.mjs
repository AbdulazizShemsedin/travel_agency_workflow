#!/usr/bin/env node
// Writes src/lib/api/v2/v1Routes.generated.ts from the backend's /openapi.json.
//
// Each /v1 route names the old operation it replaces (x-op) and which old argument each path or
// renamed query parameter fills (x-args). The table lets requestV2 send an old-style call
// (operation name + arguments) to its /v1 route.
//
// Usage: node scripts/gen-v1-routes.mjs <openapi.json path or URL>
//   The backend serves /openapi.json without a login when PUBLIC_DOCS=1.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/gen-v1-routes.mjs <openapi.json path or URL>");
  process.exit(1);
}

const text = /^https?:\/\//.test(src) ? await (await fetch(src)).text() : await readFile(src, "utf8");
const spec = JSON.parse(text);
const schemas = spec.components?.schemas || {};
const resolve = (s) => (s && s.$ref ? schemas[s.$ref.split("/").pop()] : s) || {};

const routes = {};
for (const [p, methods] of Object.entries(spec.paths || {})) {
  if (!p.startsWith("/v1/")) continue;
  for (const [m, o] of Object.entries(methods)) {
    if (!o || typeof o !== "object" || !o["x-op"]) continue;
    // "agency_tracking.upload_guard.upload_file" is keyed by its last segment, like every other op.
    const op = String(o["x-op"]).split(".").pop();
    const xargs = o["x-args"] || {};
    const pathParams = {};
    const query = {};
    for (const prm of o.parameters || []) {
      const old = xargs[prm.name] || prm.name;
      if (prm.in === "path") pathParams[prm.name] = old;
      else if (prm.in === "query") {
        const t = prm.schema?.type;
        const isArray = t === "array" || (Array.isArray(t) && t.includes("array"));
        query[prm.name] = isArray ? [old] : old;
      }
    }
    const content = o.requestBody?.content || {};
    let body = null;
    let props = null;
    if (content["multipart/form-data"]) body = "multipart";
    else if (content["application/json"]) {
      body = "json";
      const s = resolve(content["application/json"].schema);
      // A closed body refuses unknown fields; list what it accepts so the client sends only those.
      if (s.additionalProperties === false) props = Object.keys(s.properties || {});
    }
    if (routes[op]) throw new Error(`two /v1 routes for ${op}: ${routes[op].p} and ${p}`);
    routes[op] = {
      m: m.toUpperCase(),
      p,
      ...(Object.keys(pathParams).length ? { path: pathParams } : {}),
      ...(Object.keys(query).length ? { q: query } : {}),
      ...(body ? { body } : {}),
      ...(props ? { props } : {}),
      ...(o["x-answer"] ? { ans: o["x-answer"] } : {}),
    };
  }
}

const sorted = Object.fromEntries(Object.entries(routes).sort(([a], [b]) => a.localeCompare(b)));
const out = `// Generated by scripts/gen-v1-routes.mjs from the backend's /openapi.json. Do not edit by hand;
// rerun the script when the backend's /v1 routes change.
//
// op -> its /v1 route. m: HTTP method; p: path; path: {path param: old argument}; q: {query param:
// old argument, or [old argument] for a comma-separated list}; body: "json" | "multipart"; props:
// the only fields a closed JSON body accepts; ans: the field of the answer that holds the old answer.

export interface V1Route {
  m: "GET" | "POST" | "PUT" | "PATCH" | "DELETE";
  p: string;
  path?: Record<string, string>;
  q?: Record<string, string | [string]>;
  body?: "json" | "multipart";
  props?: string[];
  ans?: string;
}

export const V1_ROUTES: Record<string, V1Route> = ${JSON.stringify(sorted, null, 2)};
`;

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, "..", "src", "lib", "api", "v2", "v1Routes.generated.ts");
await writeFile(target, out);
console.log(`wrote ${Object.keys(sorted).length} routes to ${path.relative(process.cwd(), target)}`);
